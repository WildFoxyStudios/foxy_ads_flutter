def build_arb(src_data: dict, locale_code: str, translations: dict) -> dict:
    """Build an ARB dict from the Spanish template + locale-specific translations.

    Strategy: For every key in src_data (skipping @@locale and @key metadata),
    take the Spanish value. If the key has a translation in `translations`,
    override it with that translation. If the key uses ICU placeholders,
    the translation values must preserve those placeholders.
    """
    # Identify "data" keys (not @-prefixed, not @@locale)
    data_keys = [k for k in src_data.keys() if not k.startswith("@")]
    assert set(translations) - set(data_keys) == set(), "translation file has stale keys not in template"

    out = {"@@locale": locale_code}
    for k in data_keys:
        es_value = src_data[k]
        if k in translations:
            out[k] = translations[k]
        else:
            # Fallback to Spanish text so the gen-l10n fallback doesn't kick in
            out[k] = es_value
    return out


def main():
    src_data = json.loads(SRC.read_text(encoding="utf-8"))
    for locale_code, translations in TRANSLATIONS.items():
        out = build_arb(src_data, locale_code, translations)
        # The locale code maps to the ARB file name.
        # Note: "pt_BR" maps to "pt_BR" in the ARB filename "app_pt_BR.arb"
        out_path = ARB_DIR / f"app_{locale_code}.arb"
        out_path.write_text(
            json.dumps(out, indent=2, ensure_ascii=False) + "\n",
            encoding="utf-8",
        )
        print(f"Wrote {out_path} ({len(translations)} translations)")


